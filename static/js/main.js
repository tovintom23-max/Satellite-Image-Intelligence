
/*
 * Satellite Image Intelligence
 * Phase 8.3 — Homepage UI Interactions
 *
 * Features:
 * - File selection
 * - Drag and drop
 * - File validation
 * - RGB image preview
 * - Inline error messages
 * - Upload loading state
 */

(() => {
    "use strict";

    // DOM elements
    const fileInput = document.getElementById("satelliteImage");
    const browseButton = document.getElementById("browseButton");
    const uploadButton = document.getElementById("uploadButton");
    const dropzone = document.getElementById("dropzone");

    const selectedFile = document.getElementById("selectedFile");
    const fileName = document.getElementById("fileName");
    const removeFileButton = document.getElementById("removeFile");

    const clientPreview = document.getElementById("clientPreview");
    const previewImage = document.getElementById("previewImage");

    const uploadForm = document.getElementById("uploadForm");
    const feedback = document.getElementById("uploadFeedback");
    const loading = document.getElementById("uploadLoading");

    // Only initialize on pages with the upload form.
    if (
        !fileInput ||
        !browseButton ||
        !uploadButton ||
        !dropzone ||
        !selectedFile ||
        !fileName ||
        !removeFileButton ||
        !clientPreview ||
        !previewImage ||
        !uploadForm
    ) {
        return;
    }

    // Configuration: must match the Flask upload limit.
    const MAX_FILE_SIZE = 20 * 1024 * 1024;

    const ALLOWED_EXTENSIONS = new Set([
        "jpg",
        "jpeg",
        "png",
        "tif",
        "tiff"
    ]);

    const PREVIEW_EXTENSIONS = new Set([
        "jpg",
        "jpeg",
        "png"
    ]);

    let previewUrl = null;
    let isSubmitting = false;

    // Clear validation errors.
    function clearFeedback() {
        if (feedback) {
            feedback.hidden = true;
            feedback.textContent = "";
        }

        dropzone.classList.remove("is-invalid");
    }

    // Show validation errors.
    function showError(message) {
        if (feedback) {
            feedback.textContent = message;
            feedback.hidden = false;
        }

        dropzone.classList.add("is-invalid");
    }

    // Release previously allocated image preview.
    function releasePreview() {
        previewImage.onload = null;
        previewImage.onerror = null;

        if (previewUrl) {
            URL.revokeObjectURL(previewUrl);
            previewUrl = null;
        }

        previewImage.removeAttribute("src");
        clientPreview.hidden = true;
    }

    // Reset selected file and preview.
    function resetSelection() {
        if (isSubmitting) {
            return;
        }

        fileInput.value = "";
        selectedFile.hidden = true;
        fileName.textContent = "";
        uploadButton.disabled = true;

        releasePreview();
        clearFeedback();
    }

    // Convert file size into megabytes.
    function formatSize(bytes) {
        return (
            bytes / (1024 * 1024)
        ).toFixed(2) + " MB";
    }

    // Validate the selected file.
    function validateFile(file) {
        clearFeedback();
        releasePreview();

        selectedFile.hidden = true;
        uploadButton.disabled = true;

        if (!file) {
            return false;
        }

        const extension = file.name
            .split(".")
            .pop()
            .toLowerCase();

        // Validate extension.
        if (!ALLOWED_EXTENSIONS.has(extension)) {
            showError(
                "Unsupported file type. Choose JPG, JPEG, PNG, TIF or TIFF."
            );

            fileInput.value = "";
            return false;
        }

        // Validate non-empty file.
        if (file.size === 0) {
            showError("The selected file is empty.");

            fileInput.value = "";
            return false;
        }

        // Validate upload size.
        if (file.size > MAX_FILE_SIZE) {
            showError(
                "This file exceeds the 20 MB upload limit. Choose a smaller file."
            );

            fileInput.value = "";
            return false;
        }

        // Display filename and size.
        fileName.textContent =
            `${file.name} (${formatSize(file.size)})`;

        selectedFile.hidden = false;
        uploadButton.disabled = false;

        // Preview browser-supported RGB formats.
        // TIFF previews are generated by Flask.
        if (PREVIEW_EXTENSIONS.has(extension)) {
            previewUrl = URL.createObjectURL(file);

            previewImage.onload = () => {
                clientPreview.hidden = false;
            };

            previewImage.onerror = () => {
                releasePreview();

                showError(
                    "Unable to preview this image. Please verify the file before uploading."
                );
            };

            previewImage.src = previewUrl;
        }

        return true;
    }

    // Browse button.
    browseButton.addEventListener("click", () => {
        fileInput.click();
    });

    // Click anywhere on the dropzone.
    dropzone.addEventListener("click", (event) => {
        if (event.target.closest("button, input")) {
            return;
        }

        fileInput.click();
    });

    // Keyboard accessibility.
    dropzone.addEventListener("keydown", (event) => {
        const isActivationKey =
            event.key === "Enter" ||
            event.key === " ";

        if (
            isActivationKey &&
            event.target === dropzone
        ) {
            event.preventDefault();
            fileInput.click();
        }
    });

    // File input selection.
    fileInput.addEventListener("change", () => {
        validateFile(fileInput.files[0]);
    });

    // Remove selected file.
    removeFileButton.addEventListener(
        "click",
        resetSelection
    );

    // Drag-over state.
    dropzone.addEventListener("dragover", (event) => {
        event.preventDefault();

        dropzone.classList.add("dragover");
    });

    // Remove drag-over state.
    dropzone.addEventListener("dragleave", (event) => {
        if (!dropzone.contains(event.relatedTarget)) {
            dropzone.classList.remove("dragover");
        }
    });

    // Handle dropped files.
    dropzone.addEventListener("drop", (event) => {
        event.preventDefault();

        dropzone.classList.remove("dragover");

        const file = event.dataTransfer?.files?.[0];

        if (!file) {
            return;
        }

        try {
            const transfer = new DataTransfer();

            transfer.items.add(file);

            fileInput.files = transfer.files;

            validateFile(file);
        } catch (error) {
            showError(
                "Drag-and-drop is unavailable in this browser. Use Browse Files instead."
            );
        }
    });

    // Handle form submission.
    uploadForm.addEventListener("submit", (event) => {
        // Prevent duplicate submissions.
        if (isSubmitting) {
            event.preventDefault();
            return;
        }

        const selected = fileInput.files[0];

        // Check selected file without resetting the preview.
        if (!selected) {
            event.preventDefault();

            showError("Please select an image first.");
            return;
        }

        const extension = selected.name
            .split(".")
            .pop()
            .toLowerCase();

        if (
            !ALLOWED_EXTENSIONS.has(extension) ||
            selected.size === 0 ||
            selected.size > MAX_FILE_SIZE
        ) {
            event.preventDefault();

            validateFile(selected);
            return;
        }

        isSubmitting = true;

        uploadButton.disabled = true;

        uploadButton.innerHTML = `
            <span
                class="spinner-border spinner-border-sm me-2"
                aria-hidden="true">
            </span>
            Uploading...
        `;

        if (loading) {
            loading.hidden = false;
        }
    });

    console.log(
        "Satellite Image Intelligence — Phase 8.3 UI initialized."
    );
})();
