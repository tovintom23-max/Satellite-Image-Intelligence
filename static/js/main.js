console.log("Satellite Image Intelligence loaded!");


// HTML elements
const fileInput = document.getElementById("satelliteImage");

const browseButton = document.getElementById("browseButton");

const uploadButton = document.getElementById("uploadButton");

const dropzone = document.getElementById("dropzone");

const selectedFile = document.getElementById("selectedFile");

const fileName = document.getElementById("fileName");

const removeFileButton = document.getElementById("removeFile");

const clientPreview = document.getElementById("clientPreview");

const previewImage = document.getElementById("previewImage");

const uploadForm = document.getElementById("uploadForm");


// Configuration
const MAX_FILE_SIZE = 20 * 1024 * 1024;

const ALLOWED_EXTENSIONS = [
    "jpg",
    "jpeg",
    "png",
    "tif",
    "tiff"
];


// Browse files
browseButton.addEventListener("click", function () {

    fileInput.click();

});


// File selection
fileInput.addEventListener("change", function () {

    if (fileInput.files.length > 0) {

        validateSelectedFile(fileInput.files[0]);

    }

});


// Validate selected file
function validateSelectedFile(file) {

    const extension = file.name
        .split(".")
        .pop()
        .toLowerCase();


    // Check extension
    if (!ALLOWED_EXTENSIONS.includes(extension)) {

        alert("Unsupported file type. Select JPG, JPEG, PNG or TIFF.");

        resetFileSelection();

        return;

    }


    // Check file size
    if (file.size > MAX_FILE_SIZE) {

        alert("File size exceeds the 20 MB limit.");

        resetFileSelection();

        return;

    }


    if (file.size === 0) {

        alert("The selected file is empty.");

        resetFileSelection();

        return;

    }


    // Display selected file
    fileName.textContent =
        file.name + " (" + formatFileSize(file.size) + ")";

    selectedFile.hidden = false;

    uploadButton.disabled = false;


    // Preview browser-supported RGB images.
    // TIFF preview is generated by the Flask backend.
    if (["jpg", "jpeg", "png"].includes(extension)) {

        const reader = new FileReader();

        reader.onload = function (event) {

            previewImage.src = event.target.result;

            clientPreview.hidden = false;

        };

        reader.onerror = function () {

            clientPreview.hidden = true;

            alert("Unable to read the selected image.");

        };

        reader.readAsDataURL(file);

    } else {

        clientPreview.hidden = true;

        previewImage.removeAttribute("src");

    }

}


// Convert bytes into readable file size
function formatFileSize(bytes) {

    return (bytes / (1024 * 1024)).toFixed(2) + " MB";

}


// Reset file selection
function resetFileSelection() {

    fileInput.value = "";

    selectedFile.hidden = true;

    clientPreview.hidden = true;

    previewImage.removeAttribute("src");

    uploadButton.disabled = true;

}


// Remove selected file
removeFileButton.addEventListener("click", function () {

    resetFileSelection();

});


// Drag and drop
dropzone.addEventListener("dragover", function (event) {

    event.preventDefault();

    dropzone.classList.add("dragover");

});


dropzone.addEventListener("dragleave", function () {

    dropzone.classList.remove("dragover");

});


dropzone.addEventListener("drop", function (event) {

    event.preventDefault();

    dropzone.classList.remove("dragover");

    const files = event.dataTransfer.files;

    if (files.length > 0) {

        const dataTransfer = new DataTransfer();

        dataTransfer.items.add(files[0]);

        fileInput.files = dataTransfer.files;

        validateSelectedFile(files[0]);

    }

});


// Show upload progress state
uploadForm.addEventListener("submit", function (event) {

    if (!fileInput.files.length) {

        event.preventDefault();

        alert("Please select an image first.");

        return;

    }

    uploadButton.disabled = true;

    uploadButton.innerHTML =
        '<span class="spinner-border spinner-border-sm"></span> Uploading...';

});

